-- =============================================================================================
-- account
-- =============================================================================================

CREATE TABLE account (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    version    BIGINT NOT NULL DEFAULT 0
);

-- The one current, normalized value per (account, anchor attribute) - the only resolve-identity
-- and uniqueness authority for it. AccountProfile.personId/email/emailConfirmedAt read from here.
CREATE TABLE account_anchor (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id       BIGINT       NOT NULL,
    attribute_type   VARCHAR(50)  NOT NULL,
    normalized_value VARCHAR(255) NOT NULL,
    established_at   TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT ux_account_anchor_account_type UNIQUE (account_id, attribute_type),
    CONSTRAINT ux_account_anchor_value UNIQUE (attribute_type, normalized_value),
    CONSTRAINT fk_account_anchor_account FOREIGN KEY (account_id) REFERENCES account (id) ON DELETE CASCADE
);

-- Append-only claim log: every attribute value ever asserted, with its source and level.
CREATE TABLE account_attribute (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id       BIGINT       NOT NULL,
    attribute_type   VARCHAR(50)  NOT NULL,
    attribute_value  VARCHAR(255) NOT NULL,
    normalized_value VARCHAR(255) NOT NULL,
    claim_source     VARCHAR(50)  NOT NULL,
    established_loa  VARCHAR(16),
    established_at   TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_account_attribute_account FOREIGN KEY (account_id) REFERENCES account (id) ON DELETE CASCADE
);
CREATE INDEX ix_account_attribute_account_id ON account_attribute (account_id);
-- Covers IdentityMatchingService's attribute-combination query entirely from the index.
CREATE INDEX ix_account_attribute_type_value ON account_attribute (attribute_type, normalized_value, account_id);

-- Append-only audit record of every identification run: which procedure, at which level, when,
-- and the proof anchors it produced (docs/06-ablaeufe.md, "dass und wie", never "was").
CREATE TABLE account_identification (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id    BIGINT      NOT NULL,
    method        VARCHAR(50) NOT NULL,
    achieved_loa  VARCHAR(16),
    identified_at TIMESTAMP WITH TIME ZONE NOT NULL,
    details       JSON,
    CONSTRAINT fk_account_identification_account FOREIGN KEY (account_id) REFERENCES account (id) ON DELETE CASCADE
);
CREATE INDEX ix_account_identification_account_id ON account_identification (account_id, identified_at);

-- One registered method instance. (enrollment_type, enrollment_id) points at the credential row in
-- the owning method module; deactivated rows stay, so deletion still finds every credential.
CREATE TABLE account_auth_method (
    id                 UUID         PRIMARY KEY,
    account_id         BIGINT       NOT NULL,
    method             VARCHAR(50)  NOT NULL,
    enrollment_type    VARCHAR(50)  NOT NULL,
    enrollment_id      VARCHAR(255) NOT NULL,
    active             BOOLEAN      NOT NULL,
    enrolled_under_acr VARCHAR(16),
    label              VARCHAR(100),
    details            JSON,
    created_at         TIMESTAMP WITH TIME ZONE NOT NULL,
    deactivated_at     TIMESTAMP WITH TIME ZONE,
    CONSTRAINT ck_account_auth_method_deactivation CHECK (active = (deactivated_at IS NULL)),
    CONSTRAINT fk_account_auth_method_account FOREIGN KEY (account_id) REFERENCES account (id) ON DELETE CASCADE
);
CREATE INDEX ix_account_auth_method_account_id ON account_auth_method (account_id, method);
-- Reverse direction: credential -> accounts (revocation sweeps, orphan checks per method module).
CREATE INDEX ix_account_auth_method_enrollment ON account_auth_method (enrollment_type, enrollment_id);

-- =============================================================================================
-- orchestrator (core)
