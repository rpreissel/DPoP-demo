-- Consolidated schema (docs/02-domaenenmodell.md, docs/07-betrieb.md). Sized for >= 10M accounts
-- and a long operating life; the rules below apply to every table and are not repeated per table.
--
-- Ownership
--   * One database schema per module, and every table lives in its owning module's schema. The
--     owner is therefore structural, not a naming convention somebody has to keep up: a table
--     cannot be created in the wrong place by accident, and "which module owns this?" is answered
--     by where it is, not by how it is spelled. Table names stay short because the schema already
--     carries the module (account.anchor, auth_sms.enrollment).
--   * Foreign keys exist only WITHIN a schema. A reference into another module is an indexed plain
--     column, cleaned up through that module's API (EnrollmentCleanup, AccountDeletionService),
--     never by a cross-schema cascade - that is the same rule as before, now visible in the DDL
--     itself rather than only in this comment.
--   * A long-lived credential table is <module>.enrollment, and that qualified name IS its
--     EnrollmentRef.type.
--   * The working data of one tool run is <module>.<tool role>_tool_session
--     (auth_qr.confirm_tool_session for confirm-qr-login). Its key IS the tool_session_id: the row
--     is the module's half of orchestrator.tool_session, not a fourth session level and not one
--     row per attempt - a run survives several failed attempts (AuthJourney.attempt_budget).
--
-- Account model
--   * account.account is identity key and optimistic-lock root only. Current state lives in rows
--     keyed by account (account.anchor, account.auth_method) and bumps its version when it
--     changes; history is append-only (account.attribute, account.identification) and never does.
--
-- Types and names
--   * Surrogate keys: BIGINT GENERATED BY DEFAULT AS IDENTITY for long-lived rows, UUID for
--     session-scoped rows. The key column is always "id"; a reference is "<table>_id".
--   * Points in time: TIMESTAMP WITH TIME ZONE. Enum values: VARCHAR(32). ACR levels: VARCHAR(16).
--     Tool ids, method names, attribute types, claim sources: VARCHAR(50). Digests: VARCHAR(64).
--   * Indexes and constraints are schema-scoped objects, so they carry no module prefix either:
--     ux_<table>_<cols> (unique), ix_<table>_<cols>. Every retention sweep has an index on its
--     cutoff column.

